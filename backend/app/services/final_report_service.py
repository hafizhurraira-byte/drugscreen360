def _build_payload(request: FinalProjectReportRequest, created_at: str) -> dict[str, Any]:
    if request.report_mode == "concise_disease_to_lead_report":
        return _build_payload_concise(request, created_at)
        
    context = _project_context(request.project_id)
    sections = [
        _screening_section(request),
        _training_section(request),
        _prediction_section(request),
        _external_validation_section(request),
        _domain_section(request),
        _explainability_section(request),
        _lead_section(request),
        _validation_planner_section(request),
        _experimental_feedback_section(request),
    ]
    included = [section.section_id for section in sections if section.included]
    missing = [section.section_id for section in sections if not section.included and section.summary.get("status") != "not requested"]
    warnings = list(context.get("warnings") or [])
    project_items = ((context.get("project") or {}).get("items") or []) if isinstance(context.get("project"), dict) else []
    if any((item.get("metadata") or {}).get("demo_mode") or (item.get("metadata") or {}).get("data_source") == "demo" or "demo" in str(item.get("item_type", "")) for item in project_items):
        warnings.append("Demo data for software demonstration only. Not experimental or clinical evidence.")
    for section in sections:
        warnings.extend(section.warnings)
    screening_count = next((section.summary.get("screening_run_count", 0) for section in sections if section.section_id == "screening"), 0)
    lead_top = next((section.summary.get("top_candidates", []) for section in sections if section.section_id == "lead_prioritization"), [])
    dashboard = context.get("dashboard") or {}
    next_steps = list(dashboard.get("recommended_next_steps") or [])
    if not next_steps:
        next_steps = [
            "Complete missing data before relying on computational summaries.",
            "Run or review experimental validation assays for candidates kept under consideration.",
            "Use model retraining only when enough curated and validated experimental data exists.",
        ]
    summary = FinalProjectReportSummary(
        project_name=(context.get("project") or {}).get("title") if context.get("project") else None,
        generated_at=created_at,
        molecule_or_candidate_count=int(screening_count or len(dashboard.get("candidate_matrix") or [])),
        top_candidates=lead_top[:5],
        main_findings=[
            f"Included sections: {', '.join(included) or 'none'}",
            f"Missing sections: {', '.join(missing)}" if missing else "All sections are present",
        ],
        main_warnings=list(dict.fromkeys(warnings))[:20],
        next_recommended_steps=next_steps,
    )
    return {
        "report_title": request.report_title,
        "project_id": request.project_id,
        "created_at": created_at,
        "app_version": app_version(),
        "scientific_notice": SCIENTIFIC_NOTICE,
        "executive_summary": summary.model_dump(),
        "project_context": context,
        "sections": [section.model_dump() for section in sections],
        "included_sections": included,
        "missing_sections": missing,
        "final_limitations": FINAL_LIMITATIONS,
        "reproducibility": {
            "app_version": app_version(),
            "python_version": sys.version.split()[0],
            "python_implementation": platform.python_implementation(),
            "run_command": ".\\scripts\\start_all.ps1",
            "test_command": ".\\scripts\\run_tests.ps1",
            "generated_at": created_at,
        },
        "warnings": list(dict.fromkeys(warnings)),
    }


