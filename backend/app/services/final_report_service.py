def _safe(value: Any) -> str:
    if value in (None, "", [], {}):
        return "not available"
    if isinstance(value, list):
        items = []
        for item in value:
            if isinstance(item, dict):
                name = item.get("compound_name") or item.get("name") or item.get("model_id") or item.get("task_name")
                if name:
                    items.append(str(name))
            else:
                items.append(str(item))
        if items:
            return ", ".join(items)
        return "not available"
    if isinstance(value, dict):
        pairs = []
        for k, v in value.items():
            if not isinstance(v, (dict, list)):
                pairs.append(f"{k}: {v}")
        if pairs:
            return "; ".join(pairs)
        return "available"
    return str(value)


def _rows(table: str, project_id: int | None = None, limit: int = 100) -> list[dict[str, Any]]:
    init_db()
    with get_connection() as connection:
        if project_id and table in {
            "experimental_validation_plans",
            "experimental_result_batches",
            "prediction_feedback_summaries",
            "admet_lead_prioritization_runs",
        }:
            rows = connection.execute(
                f"SELECT * FROM {table} WHERE project_id = ? ORDER BY datetime(created_at) DESC, id DESC LIMIT ?",
                (project_id, limit),
            ).fetchall()
        else:
            rows = connection.execute(
                f"SELECT * FROM {table} ORDER BY datetime(created_at) DESC, id DESC LIMIT ?",
                (limit,),
            ).fetchall()
    return [dict(row) for row in rows]


def _json_loads(value: Any, default: Any) -> Any:
    if not value:
        return default
    try:
        return json.loads(value)
    except Exception:
        return default


def _section(section_id: str, title: str, requested: bool, records: list[dict[str, Any]], summary: dict[str, Any], warnings: list[str] | None = None) -> FinalProjectReportSection:
    section_warnings = list(warnings or [])
    included = bool(requested and (records or summary))
    if requested and not included:
        section_warnings.append(f"{title} was requested but no stored records were available.")
    return FinalProjectReportSection(
        section_id=section_id,
        title=title,
        included=included,
        summary=summary if requested else {"status": "not requested"},
        records=records if requested else [],
        warnings=section_warnings,
    )


